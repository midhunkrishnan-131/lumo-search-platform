"""SQLAlchemy models for LUMO Phase 16: Intelligence Automation Engine."""

from __future__ import annotations

from datetime import datetime, timezone
import uuid

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    JSON,
    String,
    Text,
)
from sqlalchemy.orm import relationship as orm_relationship

from app.database.connection import Base


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class Automation(Base):
    """Persistent intelligence automation definition with trigger, steps, and limits."""

    __tablename__ = "automations"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    name = Column(String(200), nullable=False, index=True)
    description = Column(Text, nullable=True)
    workflow_type = Column(String(64), nullable=False, default="custom", index=True)
    trigger_type = Column(String(32), nullable=False, default="manual", index=True)
    trigger_config = Column(JSON, nullable=False, default=dict)
    steps = Column(JSON, nullable=False, default=list)
    output_config = Column(JSON, nullable=False, default=dict)
    enabled = Column(Boolean, nullable=False, default=True, index=True)
    max_executions_per_day = Column(Integer, nullable=False, default=24)
    timeout_seconds = Column(Integer, nullable=False, default=120)
    max_retries = Column(Integer, nullable=False, default=1)
    version = Column(Integer, nullable=False, default=1)
    last_run_at = Column(DateTime(timezone=True), nullable=True)
    next_run_at = Column(DateTime(timezone=True), nullable=True, index=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    updated_at = Column(DateTime(timezone=True), nullable=False, default=utc_now, onupdate=utc_now)

    executions = orm_relationship(
        "AutomationExecution",
        back_populates="automation",
        cascade="all, delete-orphan",
    )


class AutomationExecution(Base):
    """Execution history record for a single automation run."""

    __tablename__ = "automation_executions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    automation_id = Column(
        String(36),
        ForeignKey("automations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    trigger_source = Column(String(64), nullable=False, default="manual")
    status = Column(String(32), nullable=False, default="pending", index=True)
    current_step_index = Column(Integer, nullable=False, default=0)
    total_steps = Column(Integer, nullable=False, default=0)
    retry_count = Column(Integer, nullable=False, default=0)
    context_data = Column(JSON, nullable=False, default=dict)
    output_summary = Column(Text, nullable=True)
    workspace_item_id = Column(String(36), nullable=True)
    error_message = Column(Text, nullable=True)
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now, index=True)

    automation = orm_relationship("Automation", back_populates="executions")
    step_logs = orm_relationship(
        "AutomationExecutionStep",
        back_populates="execution",
        cascade="all, delete-orphan",
        order_by="AutomationExecutionStep.id.asc()",
    )

    __table_args__ = (
        Index("ix_auto_exec_status_created", "status", "created_at"),
    )


class AutomationExecutionStep(Base):
    """Per-step execution log and output for observability and debugging."""

    __tablename__ = "automation_execution_steps"

    id = Column(Integer, primary_key=True, autoincrement=True)
    execution_id = Column(
        String(36),
        ForeignKey("automation_executions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    step_id = Column(String(64), nullable=False)
    step_type = Column(String(64), nullable=False)
    status = Column(String(32), nullable=False, default="pending")
    input_summary = Column(Text, nullable=True)
    output_summary = Column(Text, nullable=True)
    duration_ms = Column(Float, nullable=False, default=0.0)
    error_message = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)

    execution = orm_relationship("AutomationExecution", back_populates="step_logs")


class AutomationNotification(Base):
    """Internal LUMO notification generated by automation runs and events."""

    __tablename__ = "automation_notifications"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    automation_id = Column(
        String(36),
        ForeignKey("automations.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    execution_id = Column(String(36), nullable=True, index=True)
    event_type = Column(String(64), nullable=False, default="completed")
    title = Column(String(255), nullable=False)
    message = Column(Text, nullable=False, default="")
    is_read = Column(Boolean, nullable=False, default=False, index=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now, index=True)
